  /// جلب المناسبات ليوم هجري معين
  static List<Occasion> getOccasionsForHijriDay(int month, int day) {
    return allOccasions
        .where((occ) => occ.hijriMonth == month && occ.hijriDay == day)
        .toList();
  }

  /// جلب جميع مناسبات شهر هجري معين
  static List<Occasion> getOccasionsForHijriMonth(int month) {
    final list = allOccasions
        .where((occ) => occ.hijriMonth == month)
        .toList();
    list.sort((a, b) => a.hijriDay.compareTo(b.hijriDay));
    return list;
  }
